const assert = require('node:assert/strict');
const { clicarCalculo } = require('./helpers/calculo.cjs');
module.exports = async ({ browser, baseURL }) => {
  const { criarEstadoDemo } = await import('../database/demo/state.mjs');
  const context=await browser.newContext({timezoneId:'America/Sao_Paulo',reducedMotion:'reduce'});
  try {
    await context.route('https://**/*',r=>r.abort());
    const page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.clock.install({time:new Date('2026-10-28T12:00:00Z')});
    await page.goto(baseURL);await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
    await page.evaluate(s=>localStorage.setItem('fintria-escala-dp-v2',JSON.stringify(s)),criarEstadoDemo());
    await page.reload();await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
    const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('fintria-escala-dp-v2')));
    const inicial=await saved();
    await page.locator('#cfg-modelo').selectOption('fixa');
    assert.equal(await page.locator('#cfg-mes').isVisible(),false);
    assert.equal(await page.locator('#cfg-referencia-fixa').isVisible(),true);
    assert.equal(await page.locator('[data-etapa-link="sec-feriados"]').isVisible(),false);
    assert.match(await page.locator('#etapas-status').textContent(),/1 de 7/);
    assert.deepEqual((await saved()).feriados,inicial.feriados);
    await page.locator('[data-etapa-link="sec-tipo"]').click();
    await page.locator('#etapa-proxima').click();
    assert.equal(await page.locator('#sec-jornada').isVisible(),true);
    assert.equal(await page.locator('[data-etapa-link="sec-jornada"] .etapa-numero').textContent(),'3');
    await page.locator('[data-etapa-link="sec-folgas"]').click();
    assert.equal(await page.locator('#folga-tipo option[value="rotativa"]').isDisabled(),true);
    await page.locator('[data-etapa-link="sec-config"]').click();
    await page.locator('#btn-tutorial').click();
    assert.match(await page.locator('#tutorial-contador').textContent(),/1 de 8/);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-etapa-link][data-pendente]').count(),0);
    await page.locator('[data-etapa-link="sec-gerar"]').click();
    assert.equal(await page.locator('#conversao-periodo').isVisible(),false);
    assert.doesNotMatch(await page.locator('#proposta-resumo-grade').textContent(),/clique nas células/);
    await clicarCalculo(page,'#btn-gerar');
    assert.equal(await page.locator('#resultado-gerar [data-fixo-colaborador]').count(),5);
    assert.equal(await page.locator('#resultado-gerar [data-fixo-dia]').count(),35);
    assert.equal(await page.locator('#resultado-gerar [data-resumo-semanal]').count(),5);
    assert.match(await page.locator('#resultado-gerar').textContent(),/padrão semanal recorrente/);
    assert.equal(await page.locator('#resultado-gerar [data-ri]').count(),0);
    await clicarCalculo(page,'#btn-converter');
    const convertido=await saved();
    assert.equal(convertido.conversao.proposta.config.modeloEscala,'fixa');
    assert.equal(convertido.conversao.comparacao.status,'suficiente');
    assert.equal(await page.locator('#resultado-proposta [data-fixo-colaborador]').count(),5);
    assert.match(await page.locator('#conversao-comparacao').textContent(),/semanais/);
    const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#btn-exportar-proposta').click()]);
    assert.equal(download.suggestedFilename(),'proposta-5x2-fixa.csv');
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    const scroll=page.locator('#resultado-proposta [data-rolagem-escala]');
    assert(await scroll.evaluate(e=>e.scrollWidth>e.clientWidth));
    await page.locator('#resultado-proposta [data-ver-resumo]').click();
    assert(await scroll.evaluate(e=>e.scrollLeft>0));
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('#resultado-proposta [data-fixo-colaborador]').count(),5);
    await page.emulateMedia({media:'screen'});
    await page.reload();await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
    assert.equal((await saved()).modeloEscala,'fixa');
    assert.equal((await saved()).conversao.proposta.config.modeloEscala,'fixa');
    await page.locator('[data-etapa-link="sec-config"]').click();
    await page.locator('#cfg-modelo').selectOption('dinamica');
    assert.equal(await page.locator('#cfg-mes').isVisible(),true);
    assert.equal(await page.locator('[data-etapa-link="sec-feriados"]').isVisible(),true);
    assert.deepEqual((await saved()).feriados,inicial.feriados);
    assert.equal((await saved()).mes,inicial.mes);
    assert.match(await page.locator('#etapas-status').textContent(),/1 de 8/);
    await page.locator('[data-etapa-link="sec-gerar"]').click();
    await clicarCalculo(page,'#btn-gerar');
    assert.match(await page.locator('#resultado-gerar').textContent(),/Escala mensal/);
    assert.equal((await saved()).escalaGerada.modeloEscala,'dinamica');
    assert.deepEqual(errors,[]);
    console.log('OK: escala fixa no Worker, etapa Feriados omitida, navegação/tutorial, origem/proposta e comparação semanal, CSV, persistência, mobile/rolagem e retorno ao modo dinâmico.');
  } finally { await context.close(); }
};
