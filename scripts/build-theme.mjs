import postcss from "postcss";
import { readFile, writeFile } from "node:fs/promises";
// Derive a separate screen-only layer. Original declarations remain untouched:
// light mode and print continue using their original colors.
const files = ["utilities", "styles", "navigation", "dialogs", "motion", "workspace", "diagnosticos", "avisos-escala", "interface", "login", "theme"];
const token = /#[\da-f]{3,8}\b|(?:rgba?|hsla?)\((?:[^()]|var\([^)]*\))*\)|\bwhite\b|\bblack\b/gi;
function recolor(value, property) {
  if (property === "color") value = value.replaceAll("var(--ui-green)", "#8ee7bf");
  return value.replace(token, raw => {
    let rgb, alpha = "";
    if (raw === "white") rgb = [255,255,255];
    else if (raw === "black") rgb = [0,0,0];
    else if (raw.startsWith("#")) {
      let hex = raw.slice(1);
      if (hex.length <= 4) hex = [...hex].map(c=>c+c).join("");
      rgb = [0,2,4].map(i=>parseInt(hex.slice(i,i+2),16));
      alpha = hex.slice(6);
    } else if (raw.startsWith("hsl")) {
      const nums = raw.match(/[\d.]+/g).map(Number);
      const [h,s,l] = [nums[0]/360,nums[1]/100,nums[2]/100];
      const a=s*Math.min(l,1-l);
      const f=n=>{const k=(n+h*12)%12;return 255*(l-a*Math.max(-1,Math.min(k-3,9-k,1)));};
      rgb=[f(0),f(8),f(4)];
      if(nums.length===4)alpha=Math.round(nums[3]*255).toString(16).padStart(2,"0");
    } else {
      const nums = raw.match(/[\d.]+/g)?.map(Number);
      if (!nums || nums.length < 3) return raw;
      rgb = nums.slice(0,3);
      if(nums.length===4) alpha=Math.round(Math.min(1,nums[3])*255).toString(16).padStart(2,"0");
    }
    const [r,g,b] = rgb, max=Math.max(...rgb), min=Math.min(...rgb), light=(max+min)/510;
    const delta=max-min;
    const h=delta===0?0:((max===r?(g-b)/delta:max===g?(b-r)/delta+2:(r-g)/delta+4)*60+360)%360;
    const hue=delta<15||((property==="color"||property==="fill")&&delta<65&&h>=175&&h<255)?"neutral":h<20||h>=345?"red":h<65?"amber":h<175?"green":h<255?"blue":"purple";
    let color;
    if(property === "color" || property === "fill") {
      color = light > .84 ? "#edf3fa" : ({green:"#8ee7bf",amber:"#ffd68c",red:"#ffb0b7",purple:"#d7bcff",blue:"#a9d1ff",neutral:"#bfcede"})[hue];
      if(light < .3 && hue !== "red" && hue !== "green") color="#e6edf5";
    } else if(property.includes("border") || property.includes("outline")) {
      color = hue === "neutral" || light > .8 ? "#415770" : ({green:"#4fae8b",amber:"#bd964c",red:"#c0717c",purple:"#987cc0",blue:"#627f9f"})[hue];
    } else {
      color = light > .78 ? ({neutral:"#1b2a3b",green:"#153c31",amber:"#3e321e",red:"#432731",purple:"#322943",blue:"#20364d"})[hue] : hue === "amber" && light > .3 ? "#795114" : raw;
    }
    return color.startsWith("#") && alpha && color.length===7 ? color+alpha : color;
  });
}
export async function buildTheme(root) {
  const output = postcss.root();
  for(const file of files) {
    const css=postcss.parse(await readFile(`${root}/assets/css/${file}.css`,"utf8"));
    css.walkRules(rule=>{
      let parent=rule.parent, media=[];
      while(parent && parent.type!=="root") {
        if(parent.type==="atrule" && /keyframes|print/.test(parent.name+parent.params)) return;
        if(parent.type==="atrule") media.unshift({name:parent.name,params:parent.params});
        parent=parent.parent;
      }
      const declarations=rule.nodes.filter(n=>n.type==="decl" && /^(color|background(?:-color)?|border(?:-(?:top|right|bottom|left))?(?:-color)?|outline(?:-color)?|scrollbar-color|fill)$/.test(n.prop)).map(n=>{
        const v=recolor(n.value,n.prop); return v===n.value?null:n.clone({value:v});
      }).filter(Boolean);
      if(!declarations.length || rule.selector.includes(".theme-switch::after")) return;
      const selectors=rule.selectors.map(s => file === "login" ? (s.startsWith("body") ? s.replace(/^body/, "body.login-page") : `.login-page ${s}`) : s).map(s=>/^(html|:root)(?=[\s.:#\[]|$)/.test(s)?s.replace(/^(html|:root)/,'html[data-theme="dark"]'):`html[data-theme="dark"] ${s}`);
      const copy=postcss.rule({selectors}); copy.append(declarations);
      let target=output;
      for(const m of media) {const a=postcss.atRule(m); target.append(a);target=a;}
      target.append(copy);
    });
  }
  await writeFile(`${root}/assets/css/theme-dark.css`, `/* Generated by scripts/build-theme.mjs; edit palette there. Screen only. */\n@media screen {\nhtml[data-theme="dark"] { color-scheme:dark; --ui-ink:#e6edf5; --ui-muted:#b5c6d8; --ui-line:#415770; --ui-page:#101923; --ui-green:#167455; --ui-focus:#8acbff; }\n${output.toString()}\n}\n`);
}
